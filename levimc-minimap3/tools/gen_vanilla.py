# Генерирует src/mod/VanillaColors.h из diorama/vanilla_looks.dat (Java-мод Diorama, MIT, (c) Dara Adedeji).
# Формат: gzip; DVLT, fmt=1, N looks(30 байт: kind,tint,top,topTinted,f32,side,sideTinted,f32,constTint), блоки (UTF, props, varint looks), цветовые карты 64x64 RGB x3.
import gzip, struct, sys, collections
src = sys.argv[1]; out = sys.argv[2]
d = gzip.decompress(open(src, 'rb').read()); p = 0
def u(fmt):
    global p
    r = struct.unpack_from('>' + fmt, d, p); p += struct.calcsize('>' + fmt); return r
def utf():
    global p
    n, = u('H'); s = d[p:p+n].decode('utf-8'); p += n; return s
def varint():
    global p
    v = 0; sh = 0
    while True:
        b = d[p]; p += 1; v |= (b & 0x7F) << sh; sh += 7
        if not b & 0x80: return v
assert u('II') == (0x44564C54, 1)
n, = u('I'); looks = []
for _ in range(n):
    kind, tint, top, topT, topW, side, sideT, sideW, ct = u('bbIIfIIfI'); looks.append((kind, tint, top, topT, topW, side, sideT, sideW, ct))
nb, = u('I'); blocks = {}
for _ in range(nb):
    name = utf(); ns, = u('B'); [utf() for _ in range(ns)]; cnt, = u('I'); ids = [varint() for _ in range(cnt)]
    blocks[name] = ids
mc, = u('B'); maps = []
for _ in range(mc):
    ok, = u('?')
    if ok:
        m = [(d[p+3*i] << 16) | (d[p+3*i+1] << 8) | d[p+3*i+2] for i in range(64*64)]; p += 3*64*64; maps.append(m)
    else: maps.append(None)
# одна запись на блок: самый частый look среди состояний (для воды/ступеней/дверей это корректно для карты сверху)
used = {}; order = []
def lid(i):
    if i not in used: used[i] = len(order); order.append(i)
    return used[i]
rows = []
for name in sorted(blocks):
    cand = blocks[name]
    tinted = [i for i in cand if looks[i][1] > 0]
    c = collections.Counter(tinted or cand).most_common(1)[0][0]
    rows.append((name.replace('minecraft:', ''), lid(c)))
with open(out, 'w', encoding='utf-8') as f:
    f.write('// GENERATED by tools/gen_vanilla.py from Diorama (MIT, (c) Dara Adedeji) vanilla_looks.dat. Do not edit.\n#pragma once\n#include <cstdint>\nnamespace minimap3::vanilla {\n')
    f.write('struct Look { int8_t kind, tint; uint32_t top, topTinted; float topW; uint32_t side, sideTinted; float sideW; uint32_t constTint; };\n')
    f.write('// kind: 0 air,1 solid,2 water,3 lava,4 glass,5 plant; tint: 0 none,1 grass,2 foliage,3 dry foliage,4 water\n')
    f.write('inline constexpr Look kLooks[] = {\n')
    for i in order:
        k, t, a, b, w, s, e, w2, c = looks[i]
        f.write('{%d,%d,0x%08Xu,0x%08Xu,%.6ff,0x%08Xu,0x%08Xu,%.6ff,0x%08Xu},\n' % (k, t, a, b, w, s, e, w2, c))
    f.write('};\nstruct Entry { char const* name; uint16_t look; };\ninline constexpr Entry kBlocks[] = {\n')
    for name, l in rows: f.write('{"%s",%d},\n' % (name, l))
    f.write('};\ninline constexpr int kBlockCount = %d;\n' % len(rows))
    names = ['grass', 'foliage', 'dry_foliage']
    for i, m in enumerate(maps):
        if m is None: continue
        f.write('inline constexpr uint32_t kMap_%s[64*64] = {%s};\n' % (names[i], ','.join('0x%06X' % v for v in m)))
    f.write('} // namespace minimap3::vanilla\n')
print('looks used', len(order), 'blocks', len(rows), 'maps', [m is not None for m in maps])
