#!/usr/bin/env python3
"""Generates _generated/*.md reference tables from the unpacked addon. Usage: build_docs.py <addon_root> <catalog.json> <out_dir>"""
import os,sys,json,re,collections,posixpath
root,catp,out=sys.argv[1:4]; os.makedirs(out,exist_ok=True)
BP=os.path.join(root,'Trackwork_RZ_BP'); RP=os.path.join(root,'Trackwork_RZ_RP')
cat=json.load(open(catp))
def jl(p):
    try: return json.load(open(p,encoding='utf-8-sig'))
    except Exception: return None
def w(name,txt): open(os.path.join(out,name),'w',encoding='utf-8').write(txt)
# --- modules + deps
def res(src,imp): return posixpath.normpath(posixpath.join(posixpath.dirname(src),imp)) if imp.startswith('.') else imp
g={k:sorted({res(k,i['from']) for i in v['imports'] if i['from'].startswith('.')}) for k,v in cat.items()}
rev=collections.defaultdict(list)
for k,ds in g.items():
    for d in ds: rev[d].append(k)
seen={'main.js'};st=['main.js']
while st:
    k=st.pop()
    for d in g.get(k,[]):
        if d in cat and d not in seen: seen.add(d);st.append(d)
L=['# Module catalog (generated by tools/build_docs.py)\n','Reachable = imported (transitively) from `main.js`. `physics.js` is reached via `api/physics.js` / `main.js` imports.\n','| module | KB | lines | funcs | reachable | imported by | event subs |','|---|---|---|---|---|---|---|']
for k,v in sorted(cat.items()):
    L.append(f"| `{k}` | {v['bytes']//1024} | {v['lines']} | {len(v['functions'])} | {'yes' if k in seen else '**DEAD**'} | {', '.join(rev[k][:4])}{'…' if len(rev[k])>4 else ''} | {len(v['events'])} |")
w('modules.md','\n'.join(L)+'\n')
L=['# Exports per module\n']
for k,v in sorted(cat.items()):
    if v['exports']: L.append(f"- `{k}`: "+', '.join(f'`{e}`' for e in v['exports']))
w('exports.md','\n'.join(L)+'\n')
# --- blocks / entities / items
rows=['| id | states | components (keys) | custom components |','|---|---|---|---|']
nb=0
for f in sorted(os.path.relpath(os.path.join(r,x),f'{BP}/blocks') for r,_,xs in os.walk(f'{BP}/blocks') for x in xs):
    p=f'{BP}/blocks/{f}'
    if not f.endswith('.json'): continue
    d=jl(p); 
    if not d: rows.append(f'| `{f}` | PARSE ERR | | |'); continue
    b=d.get('minecraft:block',{}); desc=b.get('description',{}); comps=b.get('components',{})
    rows.append(f"| `{desc.get('identifier',f)}` | {', '.join(desc.get('states',{}).keys())[:120]} | {', '.join(k.replace('minecraft:','') for k in list(comps)[:8])} | {', '.join(c for c in comps if ':' in c and not c.startswith('minecraft:'))} |"); nb+=1
w('blocks.md',f'# Blocks ({nb})\n\n'+'\n'.join(rows)+'\n')
ents=collections.defaultdict(list)
for f in sorted(os.path.relpath(os.path.join(r,x),f'{BP}/entities') for r,_,xs in os.walk(f'{BP}/entities') for x in xs):
    d=jl(f'{BP}/entities/{f}')
    if not d: continue
    desc=d.get('minecraft:entity',{}).get('description',{}); i=desc.get('identifier',f); ents[i.split(':')[0]+':'+re.sub(r'_[a-z0-9]{1,4}$','',i.split(':')[1])[:0]].append((i,desc.get('runtime_identifier',''),list(desc.get('properties',{}).keys())))
L=['# Server entities (BP/entities)\n',f'Total files: {sum(len(v) for v in ents.values())}. Many are per-variant clones (cbc_*).\n','| id | runtime | properties |','|---|---|---|']
for ns,v in ents.items():
    for i,r,p in v[:400]: L.append(f"| `{i}` | {r} | {', '.join(p)[:100]} |")
w('entities_bp.md','\n'.join(L)+'\n')
L=['# Items (BP/items)\n','| id | category | components |','|---|---|---|']
for f in sorted(os.path.relpath(os.path.join(r,x),f'{BP}/items') for r,_,xs in os.walk(f'{BP}/items') for x in xs):
    d=jl(f'{BP}/items/{f}')
    if not d: continue
    it=d.get('minecraft:item',{}); L.append(f"| `{it.get('description',{}).get('identifier',f)}` | {it.get('description',{}).get('menu_category',{}).get('category','')} | {', '.join(k.replace('minecraft:','') for k in it.get('components',{}))[:100]} |")
w('items.md','\n'.join(L)+'\n')
L=['# Recipes (BP/recipes)\n','| id | type | result | ingredients |','|---|---|---|---|']
for f in sorted(os.path.relpath(os.path.join(r,x),f'{BP}/recipes') for r,_,xs in os.walk(f'{BP}/recipes') for x in xs):
    d=jl(f'{BP}/recipes/{f}')
    if not d: continue
    k=[x for x in d if x.startswith('minecraft:recipe')]
    if not k: continue
    r=d[k[0]]; res_=r.get('result'); res_=res_.get('item') if isinstance(res_,dict) else res_
    ing=r.get('ingredients') or r.get('key') or {}
    ing=[x.get('item') for x in ing] if isinstance(ing,list) else [v.get('item') for v in ing.values()]
    L.append(f"| `{r.get('description',{}).get('identifier',f)}` | {k[0].split(':')[1]} | `{res_}` | {', '.join(str(i) for i in ing)[:140]} |")
w('recipes.md','\n'.join(L)+'\n')
# --- client entities / resource pack
L=['# Resource pack overview\n']
for sub in ['entity','render_controllers','animations','animation_controllers','models','attachables','particles','textures','sounds','materials','ui','texts']:
    n=sum(len(x) for _,_,x in os.walk(f'{RP}/{sub}')) if os.path.isdir(f'{RP}/{sub}') else 0
    L.append(f'- `{sub}/`: {n} files')
L.append('\n## Client entities (RP/entity)\n')
for f in sorted(os.path.relpath(os.path.join(r,x),f'{RP}/entity') for r,_,xs in os.walk(f'{RP}/entity') for x in xs):
    d=jl(f'{RP}/entity/{f}')
    if not d: continue
    de=d.get('minecraft:client_entity',{}).get('description',{})
    L.append(f"- `{de.get('identifier',f)}` geometry={list((de.get('geometry') or {}).keys())[:3]} rc={(de.get('render_controllers') or [])[:2]}")
w('resource_pack.md','\n'.join(L[:1200])+'\n')
# --- events / dynprops / scriptevents (from raw scan of text)
sev=collections.defaultdict(set); dyn=collections.defaultdict(set); ev=collections.defaultdict(set)
sd=f'{BP}/scripts'
for k in cat:
    s=open(f'{sd}/{k}',encoding='utf8',errors='replace').read()
    for m in re.finditer(r'\b(?:world\d*|system\d*)\.(afterEvents|beforeEvents)\.(\w+)\.subscribe',s): ev[(m.group(1),m.group(2))].add(k)
    for m in re.finditer(r'(?:get|set)DynamicProperty\(\s*(?:["\']([\w:.\-]+)["\']|`([\w:.\-${}]+)`)',s): dyn[m.group(1) or m.group(2)].add(k)
    if 'scriptEventReceive' in s:
        for m in re.finditer(r'\.id\s*(?:!==?|===?)\s*["\']([\w:]+)["\']|\.id\.startsWith\(\s*["\']([\w:]+)["\']|\[\s*((?:["\'][\w:]+["\']\s*,?\s*)+)\]\.includes\([^)]*\.id',s):
            for x in (m.group(1),m.group(2)): 
                if x: sev[x].add(k)
            if m.group(3):
                for x in re.findall(r'["\']([\w:]+)["\']',m.group(3)): sev[x].add(k)
w('events.md','# Event subscriptions\n\n| event | files |\n|---|---|\n'+'\n'.join(f"| {a}.{b} | {', '.join(sorted(v))} |" for (a,b),v in sorted(ev.items()))+'\n')
w('dynamic_properties.md','# Dynamic property keys\n\n| key | files |\n|---|---|\n'+'\n'.join(f"| `{k}` | {', '.join(sorted(v))} |" for k,v in sorted(dyn.items()))+'\n')
w('scriptevents.md','# scriptevent ids / switch-cases (heuristic regex)\n\n| id | files |\n|---|---|\n'+'\n'.join(f"| `{k}` | {', '.join(sorted(v))} |" for k,v in sorted(sev.items()))+'\n')
# --- strings table
s=open(f'{sd}/i18n/strings.js',encoding='utf8').read()
m=re.search(r'export const S = (\[.*\]);',s,re.S)
if m:
    S=json.loads(m.group(1)); L=[f'# i18n table S[id] = [ru,en,es] ({len(S)} entries)\n','Code calls `__t(id)`; look the number up here.\n','| id | ru | en |','|---|---|---|']
    for i,x in enumerate(S): L.append(f"| {i} | {x[0][:110].replace('|','\\|').replace(chr(10),' ')} | {(x[1] if len(x)>1 else '')[:110].replace('|','\\|').replace(chr(10),' ')} |")
    w('strings.md','\n'.join(L)+'\n'); print('strings',len(S))
# --- step journal (author's "шаг N" comments)
steps=collections.defaultdict(list)
for k in cat:
    for i,l in enumerate(open(f'{sd}/{k}',encoding='utf8',errors='replace')):
        for m in re.finditer(r'шаг\s+(\d+)[:\s]*([^\n]{0,140})',l):
            if len(steps[int(m.group(1))])<4: steps[int(m.group(1))].append(f'{k}:{i+1}: {m.group(2).strip()}')
w('step_journal.md','# Author "шаг N" journal (comments)\n\n'+'\n'.join(f"## step {n}\n"+'\n'.join('- '+x for x in v) for n,v in sorted(steps.items()))+'\n')
print('ok',nb,len(steps))
